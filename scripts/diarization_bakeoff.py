def run_score(a: argparse.Namespace) -> int:
    gold_map = sd.parse_speaker_map(a.gold_map)
    gold = load_gold(Path(a.gold), gold_map, a.near, Path(a.source) if a.source else None)
    audio_sha = gold.doc["source"]["audio_sha256"]
    stored = identity_check(gold, a.near)
    arms = [load_arm(Path(p), audio_sha) for p in a.provenance]
    seen = set()
    for arm in arms:
        if arm.key in seen:
            raise Refused(f"{arm.key} is given twice")
        seen.add(arm.key)
    out_dir = Path(a.out_dir) if a.out_dir else None
    scored: Dict[str, Dict[str, Any]] = {STORED_ARM: stored}
    for arm in arms:
        scored[arm.key] = score_arm(gold, arm, a.near, out_dir)

    # One result per arm for the bar: the worse run if runs differ (plan §2).
    by_arm: Dict[str, List[str]] = {}
    for arm in arms:
        by_arm.setdefault(arm.name, []).append(arm.key)
    determinism, per_arm = {}, {}
    for name, keys in by_arm.items():
        shas = {scored[k]["arm"]["turns_sha256"] for k in keys}
        pick = scored[keys[0]]
        for k in keys[1:]:
            pick = worse(pick, scored[k])
        determinism[name] = {"runs": keys, "identical": len(shas) == 1,
                             "scored": f"{pick['arm']['name']}/{pick['arm']['run']}"}
        per_arm[name] = pick
    # The baseline is community-1 at its better: the stored turns, or a rerun if better.
    baseline = stored
    for k in by_arm.get("community1", []):
        if scored[k]["words"]["student_as_instructor"] < baseline["words"]["student_as_instructor"]:
            baseline = scored[k]
    challengers = {n: r for n, r in per_arm.items() if n != "community1"}
    result = {
        "plan": "docs/diarization_bakeoff_plan.md",
        "gold": str(gold.path), "gold_sha256": sha256_file(gold.path),
        "source": gold.labels["source"], "source_sha256": gold.labels["source_sha256"],
        "gold_map": gold_map, "near_words": a.near,
        "identity": headline(stored),
        "baseline": {"arm": f"{baseline['arm']['name']}/{baseline['arm']['run']}", **headline(baseline)},
        "arms": scored, "determinism": determinism,
        "verdict": verdict(baseline, challengers),
    }
    for ln in summary(result):
        print(ln)
    if a.json:
        Path(a.json).write_text(json.dumps(result, indent=1) + "\n")
        print(f"wrote {a.json}")
    return 0


def run_convert(a: argparse.Namespace) -> int:
    turns = convert(Path(a.input).read_text(), a.format)
    labels = sorted({t["speaker"] for t in turns})
    print(f"{len(turns)} turns, {len(labels)} labels: {', '.join(labels)}")
    if a.out:
        Path(a.out).write_text(json.dumps(turns, indent=1) + "\n")
        print(f"wrote {a.out}")
    return 0


def main(argv: Optional[List[str]] = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("convert", help="one native output -> speaker_turns")
    c.add_argument("input")
    c.add_argument("--format", required=True, choices=sorted(FORMATS))
    c.add_argument("--out", default=None, help="write the turns here as JSON")
    s = sub.add_parser("score", help="score every arm against the gold")
    s.add_argument("gold", help="the gold *_labels.json (the normalized, checked one)")
    s.add_argument("provenance", nargs="*", help="each arm run's provenance.json (run_arm.py wrote it)")
    s.add_argument("--gold-map", required=True,
                   help="the map the gold was scored with, e.g. SPEAKER_01=L,SPEAKER_00=S")
    s.add_argument("--source", default=None, help="the gold's raw JSON, if not where the labels say")
    s.add_argument("--near", type=int, default=sd.NEAR_WORDS)
    s.add_argument("--out-dir", default=None, help="write each arm's swapped raw-JSON copy here (holds text)")
    s.add_argument("--json", default=None, help="also write the numbers here")
    a = p.parse_args(argv)
    try:
        return run_score(a) if a.cmd == "score" else run_convert(a)
    except (Refused, OSError, ValueError, KeyError) as exc:
        print(f"refused: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
