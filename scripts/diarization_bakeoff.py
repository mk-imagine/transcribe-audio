#!/usr/bin/env python3
"""Diarization bake-off: convert each arm's native output and score it against the gold.

    python3 scripts/diarization_bakeoff.py convert --format rttm X.rttm --out X_turns.json
        -> one arm's native output as the schema's ``speaker_turns``
    python3 scripts/diarization_bakeoff.py score GOLD_labels.json --gold-map SPEAKER_01=L,SPEAKER_00=S \\
        transcripts/bakeoff/<stem>/<arm>/run1/provenance.json [...] --out-dir DIR --json FILE
        -> every arm scored through the same stage 2 and the same scorer, and the bar

Pre-registered in docs/diarization_bakeoff_plan.md, which fixes the arms, the
data path, the speaker-map rule, the metrics and the bar. This file implements
that plan; a change to anything in it after the arms have run is post-hoc.

**The data path.** The gold's raw JSON keeps its ``words`` and its
``secondary_stream``; only ``speaker_turns`` (and the ``diarization`` block that
describes them) is replaced by an arm's output, in a *copy* written to
``--out-dir`` (D3: the original record is never rewritten). Stage 2 is then the
render the gold was labeled on -- the lecture profile's stream, ``assign`` plus
``smooth`` at their defaults -- regenerated by ``diarization_labels.build``, so
the diarizer is the only thing that varies.

**The truth** is derived once, from the gold, exactly as
``score_diarization.py`` derives it (the gold's own render, its verdicts and
markers, and ``--gold-map``, the map the gold was scored with). It is a speaker
per word, and the words are the same for every arm.

**An arm's boundaries** are its own rendered label changes. Each gets a verdict
from the truth: ``real`` where the true speaker changes at that word,
``spurious`` where it does not, ``unsure`` where either side is unknown. That is
the gold's convention (diarization_repair_plan.md §1.7, answer 3) read off the
truth, so the gold's stored turns put through this path must reproduce the
scorer's own numbers exactly. ``score`` checks this first and refuses
otherwise (the identity check).

**The speaker map** for an arm is not given: it is computed from the gold, by
the same rule for every arm (``map_labels``): the optimal one-to-one pairing of
labels with gold identities (the DER convention), then every leftover label
folded into the identity it shares the most words with.

Pure Python, no model, no dependencies beyond stage 2 and the scorer. The
outputs hold counts, labels, word indices and times, never transcript text;
the raw-JSON copies written to ``--out-dir`` do hold text, so point it into
``transcripts/`` (gitignored).

Exit codes: 0 ok; 2 refused (a malformed native output, a provenance file whose
output or audio does not match, a gold that fails the identity check, an arm
whose render does not cover the gold's words).
"""

